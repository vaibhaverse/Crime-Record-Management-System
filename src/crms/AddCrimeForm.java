    private void addCrime() {
        String caseNumber = caseNumberField.getText().trim();
        String crimeType = (String) crimeTypeBox.getSelectedItem();
        String description = descriptionArea.getText().trim();
        String crimeDate = dateField.getText().trim();
        String location = locationField.getText().trim();
        String status = (String) statusBox.getSelectedItem();

        // Validation
        if (caseNumber.isEmpty() || description.isEmpty() || crimeDate.isEmpty() || location.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields are required!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Connection conn = DatabaseConnector.connect();
        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Database connection failed!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            String sql = "INSERT INTO crimes (case_number, crime_type, description, crime_date, location, status) VALUES (?, ?, ?, ?, ?, ?)";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, caseNumber);
            pstmt.setString(2, crimeType);
            pstmt.setString(3, description);
            pstmt.setString(4, crimeDate);
            pstmt.setString(5, location);
            pstmt.setString(6, status);

            int rows = pstmt.executeUpdate();
            if (rows > 0) {
                JOptionPane.showMessageDialog(this, "Crime record added successfully!");
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to add crime record!", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void clearFields() {
        caseNumberField.setText("");
        crimeTypeBox.setSelectedIndex(0);
        descriptionArea.setText("");
        dateField.setText("");
        locationField.setText("");
        statusBox.setSelectedIndex(0);
    }
    

