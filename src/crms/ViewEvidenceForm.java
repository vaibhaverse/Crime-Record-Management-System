    private void loadEvidenceData() {
        try {
            Connection conn = DatabaseConnector.getConnection();
            String query = "SELECT * FROM Evidence";
            PreparedStatement stmt = conn.prepareStatement(query);
            ResultSet rs = stmt.executeQuery();

            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{"Evidence ID", "Crime ID", "Description", "Type", "Submitted By", "Submission Date"});

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("evidence_id"),
                    rs.getInt("crime_id"),
                    rs.getString("description"),
                    rs.getString("evidence_type"),
                    rs.getString("submitted_by"),
                    rs.getDate("submission_date")
                });
            }

            evidenceTable.setModel(model);
            conn.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading evidence data.");
        }
    }
    
    private void searchEvidence() {
    try {
        String input = searchField.getText().trim();
        
        // Check if the input is empty or not a valid integer
        if (input.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Crime ID cannot be empty.");
            return;
        }

        // Check if the input is a valid integer
        int crimeId;
        try {
            crimeId = Integer.parseInt(input);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter a valid numeric Crime ID.");
            return;
        }

        // Proceed with the query
        Connection conn = DatabaseConnector.getConnection();
        String query = "SELECT * FROM Evidence WHERE crime_id = ?";
        PreparedStatement stmt = conn.prepareStatement(query);
        stmt.setInt(1, crimeId);
        ResultSet rs = stmt.executeQuery();

        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(new String[]{"Evidence ID", "Crime ID", "Description", "Type", "Submitted By", "Submission Date"});

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("evidence_id"),
                rs.getInt("crime_id"),
                rs.getString("description"),
                rs.getString("evidence_type"),
                rs.getString("submitted_by"),
                rs.getDate("submission_date")
            });
        }

        evidenceTable.setModel(model);
        conn.close();
    } catch (SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error occurred while loading evidence.");
    }
    }
