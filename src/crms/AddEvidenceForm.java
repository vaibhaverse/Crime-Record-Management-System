    // Populate Crime ID Dropdown
    private void loadCrimeIds() {
        try (Connection conn = DatabaseConnector.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT crime_id FROM Crimes")) {
            while (rs.next()) {
                crimeIdComboBox.addItem(rs.getString("crime_id"));
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading Crime IDs.");
        }
    }
    
    // Add Evidence to the Database
    private void addEvidence() {
        String crimeId = (String) crimeIdComboBox.getSelectedItem();
        String description = descriptionArea.getText();
        String evidenceType = evidenceTypeField.getText();
        String submittedBy = submittedByField.getText();
        String submissionDate = submissionDateField.getText();

        // Input Validation
        if (description.isEmpty() || submissionDate.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Description and Submission Date are required.");
            return;
        }
        
        if (description.isEmpty() || submissionDate.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Description and Submission Date are required.");
            return;
        }
    
        if (crimeId == null || crimeId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a valid Crime ID.");
            return;
        }

        if (!submissionDate.matches("\\d{4}-\\d{2}-\\d{2}")) {
            JOptionPane.showMessageDialog(this, "Please enter a valid submission date (YYYY-MM-DD).");
            return;
        }

        String query = "INSERT INTO Evidence (crime_id, description, evidence_type, submitted_by, submission_date) " +
                       "VALUES (?, ?, ?, ?, ?)";

        try (Connection conn = DatabaseConnector.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(query)) {

            pstmt.setInt(1, Integer.parseInt(crimeId));
            pstmt.setString(2, description);
            pstmt.setString(3, evidenceType.isEmpty() ? null : evidenceType);
            pstmt.setString(4, submittedBy.isEmpty() ? null : submittedBy);
            pstmt.setDate(5, Date.valueOf(submissionDate));

            int rowsInserted = pstmt.executeUpdate();
            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Evidence added successfully!");
                clearForm();
            }
        } catch (SQLException | IllegalArgumentException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error adding evidence. Check input and try again.");
        }
    }
    
    // Clear Form After Submission
    private void clearForm() {
        descriptionArea.setText("");
        evidenceTypeField.setText("");
        submittedByField.setText("");
        submissionDateField.setText("");
    }
    
