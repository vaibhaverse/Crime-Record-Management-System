    // Update crime record in the database
    private void updateCrime() {
        String crimeType = crimeTypeField.getText().trim();
        String description = descriptionArea.getText().trim();
        String crimeDate = crimeDateField.getText().trim();
        String location = locationField.getText().trim();
        String status = (String) statusComboBox.getSelectedItem();

        if (crimeType.isEmpty() || description.isEmpty() || crimeDate.isEmpty() || location.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields.");
            return;
        }

        try (Connection conn = DatabaseConnector.connect();
             PreparedStatement pstmt = conn.prepareStatement("UPDATE crimes SET crime_type = ?, description = ?, crime_date = ?, location = ?, status = ? WHERE crime_id = ?")) {

            pstmt.setString(1, crimeType);
            pstmt.setString(2, description);
            pstmt.setDate(3, Date.valueOf(crimeDate));
            pstmt.setString(4, location);
            pstmt.setString(5, status);
            pstmt.setInt(6, crimeId);

            int rowsUpdated = pstmt.executeUpdate();
            if (rowsUpdated > 0) {
                JOptionPane.showMessageDialog(this, "Crime record updated successfully!");
                dispose();
                new ViewCrimeForm(); // Go back to view form
            } else {
                JOptionPane.showMessageDialog(this, "Update failed. Crime not found.");
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error updating record: " + e.getMessage());
        }
    }

